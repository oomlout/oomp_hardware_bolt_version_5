"""Refresh the catalogue front page and navigation index from existing records.

Only README.md and navigation_oobb/README.md are written. No CAD or part files
are generated, copied or removed. The previous navigation branches are preserved.
"""
from collections import defaultdict
from pathlib import Path
import re
from string import Template
from urllib.parse import quote

import yaml

ROOT = Path(__file__).resolve().parent
FAMILIES = {
    'bolt': ('Bolts', 'Partially threaded hex-head bolts.'),
    'set_screw': ('Set screws', 'Fully threaded hex-head screws, including nylon variants.'),
    'nut': ('Nuts', 'Plain, locking, flanged, coupling and specialist nuts.'),
    'washer': ('Washers', 'Plain and large-diameter washers.'),
    'threaded_rod': ('Threaded rod', 'Threaded rod records by diameter and length.'),
}


def natural_key(value):
    return [int(piece) if piece.isdigit() else piece.casefold() for piece in re.split(r'(\d+)', value)]


def write_changed(path, content):
    content = content.rstrip() + '\n'
    if path.exists() and path.read_text(encoding='utf-8') == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding='utf-8', newline='\n')


def main(**kwargs):
    groups = defaultdict(list)
    loader = getattr(yaml, 'CSafeLoader', yaml.SafeLoader)
    for source in (ROOT / 'parts').glob('*/working.yaml'):
        data = yaml.load(source.read_text(encoding='utf-8'), Loader=loader)
        if not isinstance(data, dict):
            raise ValueError(f'Expected part metadata: {source}')
        family = str(data.get('taxonomy_2') or 'other')
        if not re.fullmatch(r'[a-z0-9_]+', family):
            raise ValueError(f'Unexpected hardware family: {family}')
        groups[family].append(source.parent.name)
    if not groups:
        raise ValueError('No part records found; leaving the existing pages intact')

    table = ['| Family | Browse | Records |', '| --- | --- | ---: |']
    navigation = ['<!-- Generated by working_readme.py. -->', '# Hardware catalogue', '',
                  '[Catalogue overview](../README.md) · [Canonical part folders](../parts/)', '',
                  'Choose a family, then an exact part. Every link below opens the canonical folder in `parts/`; existing navigation branches are retained.', '']
    for family in sorted(groups, key=natural_key):
        label, description = FAMILIES.get(family, (family.replace('_', ' ').title(), 'Additional hardware records.'))
        anchor = label.lower().replace(' ', '-')
        table.append(f'| {label} | [{description}](navigation_oobb/README.md#{anchor}) | {len(groups[family])} |')
        navigation.append(f'- [{label}](#{anchor}) ({len(groups[family])})')
    for family in sorted(groups, key=natural_key):
        label, _ = FAMILIES.get(family, (family.replace('_', ' ').title(), ''))
        navigation += ['', f'## {label}', '']
        for part_id in sorted(groups[family], key=natural_key):
            navigation.append(f'- [{part_id}](../parts/{quote(part_id, safe="_-.")}/)')

    template = Template((ROOT / 'presentation/README.template.md').read_text(encoding='utf-8'))
    content = template.substitute(part_count=sum(map(len, groups.values())), family_table='\n'.join(table))
    write_changed(ROOT / 'navigation_oobb/README.md', '\n'.join(navigation))
    write_changed(ROOT / 'README.md', content)
    return {'parts': sum(map(len, groups.values())), 'families': len(groups)}


if __name__ == '__main__':
    print(main())
